values ('papers', 'papers', false, 26214400, array['application/pdf'])
on conflict (id) do nothing;

drop policy if exists papers_obj_select on storage.objects;
drop policy if exists papers_obj_insert on storage.objects;
drop policy if exists papers_obj_delete on storage.objects;
create policy papers_obj_select on storage.objects for select to authenticated
  using (bucket_id = 'papers' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy papers_obj_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'papers' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy papers_obj_delete on storage.objects for delete to authenticated
  using (bucket_id = 'papers' and (storage.foldername(name))[1] = (select auth.uid())::text);
