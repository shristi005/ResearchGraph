-- ResearchGraph schema for Supabase Postgres. Run once in: Supabase Dashboard -> SQL Editor (or `supabase db push`).
-- Idempotent where practical. Contains NO destructive statements (no DROP / TRUNCATE / DELETE).
-- Vector dimension 768 = the embedding size produced by every EMBED_PROVIDER option (see docs/EMBEDDINGS.md).

create extension if not exists vector with schema extensions;

-- ---------------------------------------------------------------- profiles (1:1 with auth.users)
create table if not exists public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  email        text,
  display_name text,
  created_at   timestamptz not null default now()
);

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, display_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------- papers
create table if not exists public.papers (
  id                integer generated by default as identity primary key,
  user_id           varchar(36) not null,
  original_filename varchar(512) not null,
  stored_path       varchar(1024) not null,          -- Storage object key "<user_id>/<sha256>.pdf"
  file_hash         varchar(64) not null,
  size_bytes        integer not null,
  page_count        integer not null default 0,
  raw_text          text not null default '',
  status            varchar(32) not null default 'uploaded',
  error             text,
  pdf_title         varchar(512),
  pdf_author        varchar(512),
  layout_json       text,
  extraction_json   text,
  embedding_json    text,                             -- paper-level vector as JSON {"model","vector"}; used by graph similarity
  created_at        timestamp not null default now(),
  constraint uq_paper_user_hash unique (user_id, file_hash)
);
create index if not exists ix_papers_user on public.papers (user_id);
create index if not exists ix_papers_hash on public.papers (file_hash);

-- ---------------------------------------------------------------- chunks (+ pgvector)
create table if not exists public.chunks (
  id             integer generated by default as identity primary key,
  user_id        varchar(36) not null,
  paper_id       integer not null references public.papers(id) on delete cascade,
  idx            integer not null,
  page           integer not null,
  section        varchar(32) not null,
  text           text not null,
  embedding_json text,                                -- unused on Postgres (kept so the ORM model is shared with local SQLite)
  embed_model    varchar(80),
  embedding      extensions.vector(768)
);
create index if not exists ix_chunks_user_paper on public.chunks (user_id, paper_id);
create index if not exists ix_chunks_embedding on public.chunks using hnsw (embedding extensions.vector_cosine_ops);

-- ---------------------------------------------------------------- graph
create table if not exists public.relationships (
  id          integer generated by default as identity primary key,
  user_id     varchar(36) not null,
  source_id   integer not null references public.papers(id) on delete cascade,
  target_id   integer not null references public.papers(id) on delete cascade,
  type        varchar(32) not null,
  score       double precision,
  explanation text not null,
  shared_json text,
  created_at  timestamp not null default now(),
  constraint uq_edge unique (source_id, target_id, type)
);
create index if not exists ix_rel_user on public.relationships (user_id);
create index if not exists ix_rel_source on public.relationships (source_id);
create index if not exists ix_rel_target on public.relationships (target_id);

-- ---------------------------------------------------------------- research opportunities
create table if not exists public.hypotheses (
  id                   integer generated by default as identity primary key,
  user_id              varchar(36) not null,
  key                  varchar(40) not null,
  kind                 varchar(40) not null,
  hypothesis           text not null,
  supporting_paper_ids text not null,
  evidence             text not null,
  reasoning            text not null,
  uncertainties        text not null,
  validation_steps     text not null,
  confidence           varchar(16) not null default 'low',
  review_status        varchar(32) not null default 'new',
  details_json         text,
  feasibility_json     text,
  enrichment_status    varchar(16),
  created_at           timestamp not null default now(),
  constraint uq_hyp_user_key unique (user_id, key)
);
create index if not exists ix_hyp_user on public.hypotheses (user_id);

-- ---------------------------------------------------------------- mentor
create table if not exists public.conversations (
  id         integer generated by default as identity primary key,
  user_id    varchar(36) not null,
  title      varchar(200) not null default 'New conversation',
  created_at timestamp not null default now()
);
create index if not exists ix_conv_user on public.conversations (user_id);

create table if not exists public.messages (
  id              integer generated by default as identity primary key,
  user_id         varchar(36) not null,
  conversation_id integer not null references public.conversations(id) on delete cascade,
  role            varchar(16) not null,
  content         text not null,
  sources_json    text,
  warnings_json   text,
  created_at      timestamp not null default now()
);
create index if not exists ix_msg_user on public.messages (user_id);
create index if not exists ix_msg_conv on public.messages (conversation_id);

-- ---------------------------------------------------------------- AI result cache (content-addressed, no user data keys)
create table if not exists public.ai_cache (
  id         integer generated by default as identity primary key,
  key        varchar(64) not null unique,
  kind       varchar(32) not null,
  payload    text not null,
  created_at timestamp not null default now()
);
create index if not exists ix_ai_cache_kind on public.ai_cache (kind);

-- ---------------------------------------------------------------- Row Level Security
-- The FastAPI backend connects with the database owner role (bypasses RLS) and enforces ownership itself.
-- RLS is the second layer: anyone using the public anon/authenticated keys directly can only touch their own rows.
alter table public.profiles       enable row level security;
alter table public.papers         enable row level security;
alter table public.chunks         enable row level security;
alter table public.relationships  enable row level security;
alter table public.hypotheses     enable row level security;
alter table public.conversations  enable row level security;
alter table public.messages       enable row level security;
alter table public.ai_cache       enable row level security;   -- no policy: not reachable through the public API at all

do $$
declare t text;
begin
  foreach t in array array['papers','chunks','relationships','hypotheses','conversations','messages'] loop
    execute format('drop policy if exists %I on public.%I', t || '_owner', t);
    execute format($p$create policy %I on public.%I for all to authenticated
                      using (user_id = (select auth.uid())::text)
                      with check (user_id = (select auth.uid())::text)$p$, t || '_owner', t);
  end loop;
end $$;

drop policy if exists profiles_self on public.profiles;
create policy profiles_self on public.profiles for all to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- ---------------------------------------------------------------- vector search function (RLS applies: security invoker)
create or replace function public.match_chunks(
  query_embedding extensions.vector(768), p_paper_ids integer[], p_model text, p_limit integer default 24)
returns table (id integer, paper_id integer, page integer, section varchar, text text, similarity double precision)
language sql stable security invoker set search_path = public, extensions as $$
  select c.id, c.paper_id, c.page, c.section, c.text, 1 - (c.embedding <=> query_embedding) as similarity
  from public.chunks c
  where c.paper_id = any(p_paper_ids) and c.embed_model = p_model and c.embedding is not null
        and c.user_id = (select auth.uid())::text
  order by c.embedding <=> query_embedding
  limit p_limit
$$;

