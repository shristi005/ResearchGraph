import { useCallback, useEffect, useState } from "react";
import { ChevronDown, ChevronUp, RefreshCw, Sparkles } from "lucide-react";
import { api, errMsg } from "../api";
import { Block, Bullets, Button, Card, Chip, ErrorBox, SourceBadge } from "./ui";

/** AI Graph Overview: what the uploaded papers are about together. Facts are computed from the data; prose is AI. */
export default function GraphOverview({ refreshKey, paperCount }) {
  const [state, setState] = useState({ loading: true });
  const [open, setOpen] = useState(true);

  const load = useCallback(async (refresh = false) => {
    setState((s) => ({ ...s, loading: true }));
    try {
      const { data } = await api.get("/api/graph/overview", { params: refresh ? { refresh: true } : {} });
      setState({ loading: false, data });
    } catch (e) {
      setState({ loading: false, error: e?.response?.status === 404 ? null : errMsg(e), empty: e?.response?.status === 404 });
    }
  }, []);

  useEffect(() => { if (paperCount > 0) load(false); }, [paperCount, refreshKey, load]);

  if (paperCount === 0) return null;
  const { data, loading, error } = state;
  const ai = data?.ai;

  return (
    <Card className="mb-4 !p-4">
      <div className="flex flex-wrap items-center gap-2">
        <Sparkles size={18} className="text-terracotta" />
        <h2 className="font-display text-xl font-semibold">AI Graph Overview</h2>
        <SourceBadge kind="ai" />
        <div className="ml-auto flex gap-2">
          <Button variant="ghost" className="!px-3 !py-1" onClick={() => load(true)} loading={loading}><RefreshCw size={14} /> {ai ? "Regenerate" : "Generate"}</Button>
          <button className="rounded-lg p-1.5 hover:bg-beige" onClick={() => setOpen(!open)} aria-label={open ? "Collapse overview" : "Expand overview"}>{open ? <ChevronUp size={18} /> : <ChevronDown size={18} />}</button>
        </div>
      </div>

      {open && (
        <div className="mt-3">
          {loading && !data && <p className="animate-pulse py-4 text-sm text-ink/60">Reading across your papers… small local models can take a minute.</p>}
          <ErrorBox className="mb-2">{error}</ErrorBox>
          {data && (
            <>
              <div className="mb-3 flex flex-wrap items-center gap-1.5 text-xs">
                <span className="font-semibold">{data.facts.n_papers} papers · {data.facts.n_connections} connections.</span>
                {data.facts.common_topics.length > 0 && <span className="text-ink/60">Topics in several papers:</span>}
                {data.facts.common_topics.map((t) => <Chip key={t.term} color="#A8C3B0">{t.term} ×{t.papers}</Chip>)}
                {data.facts.common_methods.length > 0 && <span className="text-ink/60">Methods in several papers:</span>}
                {data.facts.common_methods.map((t) => <Chip key={t.term} color="#E5B5A5">{t.term} ×{t.papers}</Chip>)}
              </div>
              {data.error && <ErrorBox className="mb-2">The AI explanation is unavailable: {data.error} The counts above come straight from your papers.</ErrorBox>}
              {ai && (
                <div className={`grid gap-x-8 gap-y-1 md:grid-cols-2 ${loading ? "opacity-50" : ""}`}>
                  <Block title="What research area do these papers explore?"><p>{ai.research_area}</p></Block>
                  <Block title="What can you learn by reading them together?"><p>{ai.what_to_learn}</p></Block>
                  <Block title="Common themes"><Bullets items={ai.common_themes} empty="None identified." /></Block>
                  <Block title="Major differences"><Bullets items={ai.differences} empty="None identified." /></Block>
                  <Block title="Methods used across the papers"><Bullets items={ai.common_methods} empty="No method is shared by several papers." /></Block>
                  <Block title="Important limitations"><Bullets items={ai.key_limitations} empty="None identified." /></Block>
                </div>
              )}
              {ai && <p className="mt-1 text-xs text-ink/50">Generated by {data.model}{data.cached ? " (saved result)" : ""}. It summarises the extracted data of your papers and can contain mistakes. Open a paper to check the source.</p>}
            </>
          )}
        </div>
      )}
    </Card>
  );
}
