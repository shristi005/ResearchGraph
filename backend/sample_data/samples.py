            f"1. Introduction\n{s['intro']}\n\n2. Related Work\n{s['related']}\n\n3. Methodology\n{s['method']}\n\n"
            f"4. Results\n{s['results']}\n\n5. Limitations\n{s['limitations']}\n\n6. Conclusion\n{s['conclusion']}\n\n"
            f"7. Future Work\n{s['future']}\n\nReferences\n{refs}\n\n"
